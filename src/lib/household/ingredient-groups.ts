/**
 * The group words of "Ingredients to avoid" (HON-1343): a tag that is a group
 * word also excludes the rows the group lists. The name match alone reads
 * "sausage" as only the rows with "sausage" in their name, so it misses
 * frankfurter, chorizo and salami. `matchTag` reads this table, and
 * `pnpm db:validate` fails on a member that is not a global ingredient name.
 *
 * A group lists every member, also the rows the English word already matches
 * by name, because an Estonian household's "vorst" does not get the English
 * name match. A row is a member only when it is clearly that food. The
 * unclear cases (nut butters, peanuts, squid, veal, gelatine) are left out,
 * so a household names them as their own tags.
 */

export interface IngredientGroup {
  /** English group words, lower case, singular: "sausage". */
  en: readonly string[]
  /** Estonian group words, lower case, singular: "vorst". */
  et: readonly string[]
  /** Exact English names of global pool rows. */
  members: readonly string[]
  /**
   * Keep the Estonian part-of-word rule for the group words, so "koor" still
   * finds a household's own "kohvikoor". Without it a group word matches
   * whole words and its members only.
   */
  keepParts?: boolean
}

